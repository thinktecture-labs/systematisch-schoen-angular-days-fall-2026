#!/usr/bin/env node
/**
 * Baut die Tokens für Light und Dark und führt beide zu einer tokens.css mit
 * light-dark() zusammen. Ergebnis: ein Theme-Switch ist eine Zeile CSS
 * (`color-scheme: dark`), kein Service, kein Signal, kein effect().
 *
 * 1. Ein Style-Dictionary-Build pro Theme. Gleiche ref/sys/comp-Dateien, nur die
 *    Farbrollen-Datei unterscheidet sich → build/tokens/tokens-{light,dark}.css
 * 2. Zeilenweise zusammenführen: unterscheidet sich ein Wert zwischen den Themes,
 *    wird daraus light-dark(<light>, <dark>). Alles andere bleibt ein Wert.
 *    Dank outputReferences bleibt die Kette Component → System → Reference als var() erhalten.
 */
import StyleDictionary from 'style-dictionary';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const THEMES = ['light', 'dark'];
const TMP = 'build/tokens/';
const OUT = 'projects/ui/src/lib/styles/tokens/';

for (const theme of THEMES) {
  const sd = new StyleDictionary({
    source: [
      'tokens/ref/*.json',
      'tokens/sys/*.json',
      `tokens/sys/color/${theme}.json`,
      'tokens/comp/*.json',
    ],
    platforms: {
      css: {
        transformGroup: 'css',
        transforms: ['size/pxToRem'],
        prefix: 'md',
        buildPath: TMP,
        files: [
          {
            destination: `tokens-${theme}.css`,
            format: 'css/variables',
            options: { outputReferences: true },
          },
        ],
      },
    },
  });
  await sd.buildAllPlatforms();
}

// Eine Zeile pro Custom Property: `  --name: wert; /** optionale $description */`
const DECLARATION = /^\s*(--[\w-]+):\s*(.+?);\s*(\/\*.*?\*\/)?\s*$/gm;
const declarations = (file) =>
  Object.fromEntries(
    [...readFileSync(file, 'utf8').matchAll(DECLARATION)].map((m) => [
      m[1],
      { value: m[2], comment: m[3] ? ` ${m[3]}` : '' },
    ]),
  );
const light = declarations(`${TMP}tokens-light.css`);
const dark = declarations(`${TMP}tokens-dark.css`);

const lines = Object.entries(light).map(([name, { value, comment }]) => {
  const darkValue = dark[name]?.value;
  const themed = darkValue !== undefined && darkValue !== value;
  return `  ${name}: ${themed ? `light-dark(${value}, ${darkValue})` : value};${comment}`;
});

mkdirSync(OUT, { recursive: true });
writeFileSync(
  `${OUT}tokens.css`,
  [
    '/**',
    ' * Do not edit directly, this file was auto-generated by scripts/build-tokens.mjs.',
    ' */',
    '',
    ':root {',
    '  color-scheme: light dark;',
    ...lines,
    '}',
    '',
  ].join('\n'),
);
console.log(
  `✔︎ ${OUT}tokens.css (${lines.length} Custom Properties, davon ${lines.filter((l) => l.includes('light-dark(')).length} mit light-dark())`,
);
